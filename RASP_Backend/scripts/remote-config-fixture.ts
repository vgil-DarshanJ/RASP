/**
 * Writes the cross-language remote-config fixture (Task 10.0): configs signed
 * by this backend's own signing code, which the engine's Kotlin tests verify
 * (RaspRemoteConfigTest) and test/remoteConfig.test.ts re-checks.
 *
 *   npx tsx scripts/remote-config-fixture.ts <file> [<file> ...]
 *
 * A fresh Ed25519 key is generated for each run and thrown away: the file
 * holds the PUBLIC key and signed configs only, never a private key. Cases
 * the backend itself would refuse to publish (out of bounds, unknown field,
 * unknown detector) are signed raw on purpose, to prove the phone checks
 * them again.
 */
import crypto from "node:crypto";
import { writeFileSync } from "node:fs";
import { REMOTE_CONFIG_BOUNDS, REMOTE_MANAGEABLE_DETECTORS, SETTING_FIELDS } from "../src/remoteConfig/settings";
import { REMOTE_CONFIG_SCHEMA, signConfig } from "../src/remoteConfig/signing";

const APP = "app-fixture";
const ISSUED = new Date("2026-10-13T00:00:00.000Z");
const FAR = new Date("2099-01-01T00:00:00.000Z");
const PAST = new Date("2026-01-01T00:00:00.000Z");

const { privateKey } = crypto.generateKeyPairSync("ed25519");
const other = crypto.generateKeyPairSync("ed25519").privateKey;
const publicKey = (crypto.createPublicKey(privateKey).export({ type: "spki", format: "der" }) as Buffer).toString("base64");

const FULL = {
  detectors: { frida: false, root_jailbreak: true, vpn: true },
  pollIntervalSeconds: 10,
  heartbeatIntervalSeconds: 60,
  locationHeartbeatIntervalSeconds: 120,
  riskMediumThreshold: 25,
  riskHighThreshold: 70,
  stepUpThreshold: 50,
  highRiskTransactionMode: true,
  allowedCountries: ["IN"],
  blockedCountries: ["KP"],
  reputationRefreshHours: 12,
};

const row = (version: number, payload: unknown, expiresAt = FAR, applicationId = APP) => ({
  applicationId, version, createdAt: ISSUED, expiresAt, payload,
});

/** Signs settings exactly as given (no validation, no normalization). */
function signRaw(version: number, settings: unknown, key = privateKey) {
  const payload = JSON.stringify({
    schema: REMOTE_CONFIG_SCHEMA, applicationId: APP, version, issuedAt: ISSUED.toISOString(), expiresAt: FAR.toISOString(), settings,
  });
  return { payload, signature: crypto.sign(null, Buffer.from(payload, "utf8"), key).toString("base64"), keyId: "raw" };
}

const valid = signConfig(row(5, FULL), privateKey);
const tampered = { ...valid, payload: valid.payload.replace('"pollIntervalSeconds":10', '"pollIntervalSeconds":2') };

const fixture = {
  _comment: "Generated by FROUNTEND_BACKEND_RASPOWN/BE/scripts/remote-config-fixture.ts. Public key only; the signing key was discarded.",
  applicationId: APP,
  publicKey,
  limits: { fields: SETTING_FIELDS, detectors: REMOTE_MANAGEABLE_DETECTORS, bounds: REMOTE_CONFIG_BOUNDS },
  cases: {
    valid_v5: valid,
    valid_v6_empty: signConfig(row(6, {}), privateKey),
    older_v4: signConfig(row(4, { pollIntervalSeconds: 30 }), privateKey),
    expired_v7: signConfig(row(7, { pollIntervalSeconds: 30 }, PAST), privateKey),
    other_app_v8: signConfig(row(8, { pollIntervalSeconds: 30 }, FAR, "app-other"), privateKey),
    out_of_bounds_v9: signRaw(9, { pollIntervalSeconds: 1 }),
    unknown_field_v10: signRaw(10, { ingestionUrl: "https://attacker.example/v1/events" }),
    unknown_detector_v11: signRaw(11, { detectors: { not_a_detector: true } }),
    wrong_key_v12: signRaw(12, { pollIntervalSeconds: 30 }, other),
    tampered_v5: tampered,
  },
};

const files = process.argv.slice(2);
if (files.length === 0) {
  console.error("usage: npx tsx scripts/remote-config-fixture.ts <file> [<file> ...]");
  process.exit(2);
}
const text = `${JSON.stringify(fixture, null, 2)}\n`;
for (const file of files) writeFileSync(file, text);
console.log(`wrote ${files.length} file(s), ${Object.keys(fixture.cases).length} cases`);
